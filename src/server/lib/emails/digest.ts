/* ---------------------------------------------------------------------------
   The Monday email
   ---------------------------------------------------------------------------
   The product's answer to "what changed while I wasn't looking". It is a
   summary, not a dashboard: three themes, three quotes, one number. Anything
   longer gets skimmed and then filtered.

   Nothing here is generated by the model. Every figure is arithmetic over rows
   that already exist, so the email costs nothing to produce and cannot
   hallucinate a trend.
--------------------------------------------------------------------------- */

const { INK, STEEL, LINE, MINT, MINT_DEEP } = emailStyles;

export type DigestProject = {
  name: string;
  total: number;
  previous: number;
  negativeShare: number;
  themes: Array<{
    id: string;
    title: string;
    itemCount: number;
    negativeShare: number;
    isNew: boolean;
  }>;
  quotes: Array<{ body: string; sentiment: string | null }>;
};

export type Digest = {
  orgName: string;
  since: Date;
  projects: DigestProject[];
  total: number;
};

/**
 * Gathers a week of activity for one organization.
 *
 * Returns null when there is nothing to say. An empty weekly email is how a
 * useful product teaches people to ignore it.
 */
export async function buildDigest(
  db: PrismaClient,
  orgId: string,
  now = new Date(),
): Promise<Digest | null> {
  const since = new Date(now);
  since.setDate(since.getDate() - 7);
  const previousSince = new Date(since);
  previousSince.setDate(previousSince.getDate() - 7);

  const org = await db.organization.findUnique({
    where: { id: orgId },
    select: { name: true, projects: { select: { id: true, name: true } } },
  });
  if (!org) return null;

  const projects: DigestProject[] = [];

  for (const project of org.projects) {
    const [items, previous, themes] = await Promise.all([
      db.feedback.findMany({
        where: { projectId: project.id, createdAt: { gte: since } },
        select: {
          body: true,
          sentiment: true,
          summary: true,
          createdAt: true,
        },
        orderBy: { createdAt: "desc" },
      }),
      db.feedback.count({
        where: {
          projectId: project.id,
          createdAt: { gte: previousSince, lt: since },
        },
      }),
      db.theme.findMany({
        where: { projectId: project.id, status: "ACTIVE" },
        orderBy: { priorityScore: "desc" },
        take: 3,
        select: {
          id: true,
          title: true,
          itemCount: true,
          negativeShare: true,
          firstSeenAt: true,
        },
      }),
    ]);

    if (items.length === 0 && themes.length === 0) continue;

    const negative = items.filter((i) => i.sentiment === "NEGATIVE").length;

    projects.push({
      name: project.name,
      total: items.length,
      previous,
      negativeShare: items.length > 0 ? negative / items.length : 0,
      themes: themes.map((t) => ({
        id: t.id,
        title: t.title,
        itemCount: t.itemCount,
        negativeShare: t.negativeShare,
        isNew: t.firstSeenAt >= since,
      })),
      // Quotes are the receipts. Negative first, because those are the ones
      // worth reading on a Monday.
      quotes: [...items]
        .sort((a, b) =>
          (a.sentiment === "NEGATIVE" ? 0 : 1) -
          (b.sentiment === "NEGATIVE" ? 0 : 1),
        )
        .slice(0, 3)
        .map((i) => ({ body: i.summary ?? i.body, sentiment: i.sentiment })),
    });
  }

  const total = projects.reduce((sum, p) => sum + p.total, 0);
  if (projects.length === 0 || total === 0) return null;

  return { orgName: org.name, since, projects, total };
}

function changeLine(total: number, previous: number): string {
  if (previous === 0) {
    return total > 0 ? "first week of feedback" : "no change";
  }
  const delta = Math.round(((total - previous) / previous) * 100);
  if (delta === 0) return "level with last week";
  return `${delta > 0 ? "up" : "down"} ${Math.abs(delta)}% on last week`;
}

export function renderDigest(
  digest: Digest,
  optOutUrl: string | null = null,
): { html: string; text: string } {
  const appUrl = clientEnv.NEXT_PUBLIC_APP_URL;
  const week = digest.since.toLocaleDateString("en-US", {
    month: "long",
    day: "numeric",
  });

  const sections = digest.projects
    .map((project) => {
      const themes = project.themes
        .map((theme, index) => {
          const share = Math.round(theme.negativeShare * 100);
          return `
      <tr>
        <td style="padding:11px 0;border-bottom:1px solid ${LINE}">
          <table role="presentation" width="100%" cellpadding="0" cellspacing="0"><tr>
            <td width="22" valign="top" style="color:${STEEL};font-size:13px">${index + 1}</td>
            <td valign="top">
              <a href="${appUrl}/app/themes/${theme.id}" style="color:${INK};font-size:14.5px;font-weight:600;text-decoration:none">${escapeHtml(theme.title)}</a>
              ${theme.isNew ? `<span style="margin-left:7px;background:${MINT};color:#04231b;font-size:10.5px;font-weight:700;padding:2px 6px;border-radius:99px">NEW</span>` : ""}
              <div style="color:${STEEL};font-size:12.5px;margin-top:3px">
                ${theme.itemCount} ${theme.itemCount === 1 ? "mention" : "mentions"}${share > 0 ? ` · ${share}% negative` : ""}
              </div>
            </td>
          </tr></table>
        </td>
      </tr>`;
        })
        .join("");

      const quotes = project.quotes
        .map(
          (quote) => `
      <tr><td style="padding:8px 0">
        <div style="border-left:2px solid ${LINE};padding-left:12px;color:${STEEL};font-size:13.5px;line-height:1.6;font-style:italic">
          ${escapeHtml(quote.body.slice(0, 220))}${quote.body.length > 220 ? "…" : ""}
        </div>
      </td></tr>`,
        )
        .join("");

      return `
    <div style="margin-top:26px;padding-top:22px;border-top:1px solid ${LINE}">
      <div style="font-size:15px;font-weight:700;color:${INK}">${escapeHtml(project.name)}</div>
      <div style="font-size:13px;color:${STEEL};margin-top:3px">
        ${project.total} new ${project.total === 1 ? "piece" : "pieces"}, ${changeLine(project.total, project.previous)}
      </div>

      ${
        project.themes.length > 0
          ? `<div style="font-size:12.5px;font-weight:600;color:${MINT_DEEP};margin-top:18px">What to work on</div>
             <table role="presentation" width="100%" cellpadding="0" cellspacing="0">${themes}</table>`
          : `<div style="font-size:13px;color:${STEEL};margin-top:14px">Not enough yet for a pattern. Themes appear once the same problem shows up a few times.</div>`
      }

      ${
        project.quotes.length > 0
          ? `<div style="font-size:12.5px;font-weight:600;color:${MINT_DEEP};margin-top:20px;margin-bottom:4px">Worth reading</div>
             <table role="presentation" width="100%" cellpadding="0" cellspacing="0">${quotes}</table>`
          : ""
      }
    </div>`;
    })
    .join("");

  const body = `
    <p style="margin:0 0 6px;font-size:20px;font-weight:700;letter-spacing:-0.02em">
      ${digest.total} new ${digest.total === 1 ? "piece" : "pieces"} of feedback this week.
    </p>
    <p style="margin:0 0 20px;color:${STEEL}">
      Here's what your users have been saying since ${week}.
    </p>
    ${sections}
    <p style="margin:28px 0 0">${emailButton(`${appUrl}/app`, "Open the dashboard")}</p>`;

  const text = [
    `${digest.orgName}: ${digest.total} new ${digest.total === 1 ? "piece" : "pieces"} of feedback this week.`,
    "",
    ...digest.projects.flatMap((project) => [
      `${project.name}, ${project.total} new (${changeLine(project.total, project.previous)})`,
      ...project.themes.map(
        (theme, i) =>
          `  ${i + 1}. ${theme.title}, ${theme.itemCount} ${theme.itemCount === 1 ? "mention" : "mentions"}${theme.isNew ? " (new)" : ""}`,
      ),
      "",
    ]),
    `Open the dashboard: ${appUrl}/app`,
    "",
    "—",
    // The text part gets the same footer as the HTML. A recipient reading
    // plain text was previously given a recurring email with no sender
    // identity and no way out.
    `You're getting this because weekly digests are on for ${digest.orgName}.`,
    optOutUrl
      ? `Unsubscribe: ${optOutUrl}`
      : `Manage email preferences: ${appUrl}/app/settings/general`,
    `${site.legalEntity}, ${site.postalAddress}`,
  ].join("\n");

  return {
    html: emailShell({
      title: `Your week on ${site.name}`,
      preview: `${digest.total} new pieces of feedback, and the themes worth acting on.`,
      body,
      footer:
        `You're getting this because weekly digests are on for ${escapeHtml(digest.orgName)}. ` +
        (optOutUrl
          ? `<a href="${optOutUrl}" style="color:${STEEL}">Unsubscribe</a>, or `
          : "") +
        `<a href="${appUrl}/app/settings/general" style="color:${STEEL}">manage preferences</a>.`,
    }),
    text,
  };
}

/**
 * @param membershipId when present, the message carries a one-click
 * unsubscribe for that person. Omitted for the self-service preview, which the
 * caller asked for and should not be able to unsubscribe from.
 */
export function sendDigest(
  to: string,
  digest: Digest,
  membershipId?: string,
): Promise<SendResult> {
  const optOut = membershipId
    ? unsubscribeUrl(clientEnv.NEXT_PUBLIC_APP_URL, membershipId)
    : null;
  const { html, text } = renderDigest(digest, optOut);

  return sendEmail({
    to,
    subject: `${digest.orgName}: ${digest.total} new ${digest.total === 1 ? "piece" : "pieces"} of feedback, and what to do about it`,
    html,
    text,
    // RFC 8058: lets Gmail and Yahoo render their own unsubscribe control and
    // fire it as a POST, with no page load and no sign-in.
    ...(optOut
      ? {
          headers: {
            "List-Unsubscribe": `<${optOut}>`,
            "List-Unsubscribe-Post": "List-Unsubscribe=One-Click",
          },
        }
      : {}),
  });
}
